import { chromium } from 'playwright';
import http from 'http'; import fs from 'fs'; import path from 'path';
const MIME = { '.html':'text/html','.css':'text/css','.js':'text/javascript','.png':'image/png','.woff2':'font/woff2' };
const server = http.createServer(async (req,res)=>{ let rel=decodeURIComponent(req.url.split('?')[0]).replace(/^\//,'')||'index.html'; if(!path.extname(rel))rel+='.html'; try{const d=await fs.promises.readFile(path.join(process.cwd(),rel));res.writeHead(200,{'content-type':MIME[path.extname(rel)]||'application/octet-stream'});res.end(d);}catch{res.writeHead(404);res.end();}});
await new Promise(r=>server.listen(8951,r));
const b = await chromium.launch();
const p = await b.newPage({ viewport:{ width:390, height:844 } });
const errs = []; p.on('pageerror', e => errs.push(String(e)));
await p.goto('http://localhost:8951/index.html', { waitUntil:'load' });
await p.waitForTimeout(300);
console.log('errors:', errs.length);
console.log('gear:', await p.evaluate(() => !!document.querySelector('.settings-btn')));
await p.click('.hamburger-btn'); await p.waitForTimeout(200);
const g = await p.evaluate(() => { const el = document.querySelector('.settings-btn'); if (!el) return null; const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height }; });
console.log('gear rect:', JSON.stringify(g));
await p.click('.settings-btn'); await p.waitForTimeout(250);
console.log(await p.evaluate(() => { const pnl = document.getElementById('site-settings-root'); return { hidden: pnl && pnl.hidden, pills: document.querySelectorAll('.settings-theme-btn').length }; }));
console.log('errors:', errs.join(' | ') || 'нет');
await b.close(); server.close();
