# эвристика мусорности (та же, что при первичной классификации)
import re
STOP = re.compile(r"^(ф|фикс|фиксы|пуш|правки|wip|тест|хрень|ну посмотрим|оптимизация|оптизация|обновление|должно работать|синхронизация|карточки|маппинг|slug-эпопеи|докатка|помощь и первые шаги| site)$", re.I)

def is_garbage(subj):
    s = subj.strip()
    if STOP.match(s):
        return True
    words = s.split()
    if len(words) <= 2 and not re.search(r"[а-яa-z]{4,}\s+(и|для|из|под|по)\s+", s) and len(s) < 28:
        return True
    return False

rows = []
for line in TSV.read_text(encoding="utf-8").splitlines()[1:]:
    h, d, s, nf, ins, de, paths = line.split("\t")
    rows.append((h, d, s, int(nf), int(ins), int(de), paths))

by_hash = {r[0]: r for r in rows}

unknown = sorted(h for h in DICT if h not in by_hash)
curated_extra = sorted(
    h for h in DICT if h in by_hash and not is_garbage(by_hash[h][2]) and h not in ("f86fa86", "6e3191d", "a191f3e")
)
missing = sorted(h for h, d, s, *_ in rows if is_garbage(s) and h not in DICT)

